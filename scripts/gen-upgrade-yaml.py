#!/usr/bin/env python3
"""Regenerate deploy/upgrade.yaml from deploy/install.yaml.

upgrade.yaml is what installed storefronts apply when they update themselves
(catalog rows for oct-storefront point deployURL at it). It is install.yaml
without the one-time enable-plugin Job (not an appliable kind for older
storefronts) and without the ConfigMaps (the cluster's catalog cache and
external tools must never be overwritten).
"""
import os
import sys

import yaml

EXCLUDE = ("Job", "ConfigMap")
HEADER = """# Storefront self-update manifest: deploy/install.yaml without the one-time
# enable-plugin Job and without the ConfigMaps (the cluster's catalog cache and
# external tools must never be overwritten). Catalog rows for oct-storefront
# point deployURL here; installed storefronts apply it on Update, and every
# storefront version can apply all kinds in it.
# Generated by scripts/gen-upgrade-yaml.py; do not edit by hand.
"""


def upgrade_docs(install_path):
    docs = [d for d in yaml.safe_load_all(open(install_path)) if d]
    return [d for d in docs if d.get("kind") not in EXCLUDE]


def render(docs):
    return HEADER + "---\n".join(yaml.safe_dump(d, sort_keys=False, width=120) for d in docs)


if __name__ == "__main__":
    repo = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
    out = render(upgrade_docs(os.path.join(repo, "deploy", "install.yaml")))
    if len(sys.argv) > 1 and sys.argv[1] == "--check":
        current = open(os.path.join(repo, "deploy", "upgrade.yaml")).read()
        sys.exit(0 if current == out else 1)
    open(os.path.join(repo, "deploy", "upgrade.yaml"), "w").write(out)
